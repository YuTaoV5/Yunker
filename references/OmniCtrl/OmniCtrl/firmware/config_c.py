import json
import os
from datetime import datetime

# --- 1. 自动查找脚本所在的目录 ---
SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
# -------------------------------------------

# ---------- 2. 配置（基于脚本目录） ----------
JSON_FILE_PATH = os.path.join(SCRIPT_DIR, 'omni_manifest.json')
C_FILE_PATH = os.path.join(SCRIPT_DIR, 'bases/Src/control_config.c')
C_FILE_AUTHOR = 'Ternura_xiang'
C_FILE_EMAIL = 'ternura_xiang@foxmail.com'
# --- 结束配置 ---

def generate_file_header():
    """生成 C 文件头部的注释"""
    now = datetime.now()
    return f"""/********************************************************************************
* @author: {C_FILE_AUTHOR}
* @email: {C_FILE_EMAIL}
* @date: {now.strftime('%Y-%m-%d %H:%M')}
* @version: v1.0.0
* @description: 
* THIS FILE IS AUTOMATICALLY GENERATED BY 'config_c.py'
* DO NOT EDIT THIS FILE MANUALLY
********************************************************************************/
#include "../Inc/control_config.h"
"""

def generate_includes(modules_include_data, params_include_data):
    """生成 C 文件的 include 部分"""
    
    # 静态 include (保持不变)
    includes = [
        'methods/Inc/ctrl_factory.h',
        'methods/Inc/ctrl_registry.h',
        'methods/Inc/ctrl_wiring.h'
    ]
    
    # 1. 从 config.json 的 "modules_include" 动态生成模块的 include
    module_headers = set()
    # 遍历传入的 modules_include_data
    for header in modules_include_data:
        module_headers.add(header)

    # 2. 从 config.json 的 "params_include" 动态生成参数的 include
    param_headers = set()
    for header in params_include_data:
        param_headers.add(header)

    # 3. 组合
    include_str = ""
    include_str += "/* 导入系统方法 */\n"
    for inc in includes:
        include_str += f'#include "{inc}"\n'
    
    include_str += "/* 导入模块 */\n" 
    for inc in sorted(list(module_headers)):
        include_str += f'#include "{inc}"\n'
        
    include_str += "/* 导入系统指针变量 */\n" 
    for inc in sorted(list(param_headers)):
        include_str += f'#include "{inc}"\n'
        
    return include_str

def generate_module_init(modules_data):
    """生成 Ctrl_Config_ModuleInit 函数"""
    lines = []
    lines.append("/**\n * @description: 初始化控制模块注册表\n * @return None\n */")
    lines.append("void Ctrl_Config_ModuleInit(void)")
    lines.append("{")
    
    for module in modules_data:
        name = module['Name']
        size_type = module['Type']
        init_func = module['Init']
        c_line = f'    CtrlModule_Registry_Init({name}, sizeof({size_type}), {init_func});'
        lines.append(c_line)
        
    lines.append("}")
    return "\n".join(lines)

def generate_param_init(params_data, output_params_data):
    """生成 Ctrl_Config_ParamInit 函数"""
    lines = []
    lines.append("/**\n * @description: 初始化指针参数注册表\n * @return None\n */")
    lines.append("void Ctrl_Config_ParamInit(void)")
    lines.append("{")

    for param in params_data:
        name = param['Name']
        param_type = param['Type']
        ptr_str = param['Ptr']
        c_line = f'    CtrlModule_Registry_Param("{name}", {param_type}, &({ptr_str}), 0);'
        lines.append(c_line)
        
    for param in output_params_data:
        name = param['Name']
        ptr_str = param['Ptr']
        c_line = f'    CtrlModule_Registry_Param("{name}", CTRL_PARAM_SIGNAL_T, &({ptr_str}), 1);'
        lines.append(c_line)
        
    lines.append("}")
    return "\n".join(lines)

def main():
    print(f"Script directory is: {SCRIPT_DIR}") 
    print(f"Reading configuration from {JSON_FILE_PATH}...")
    
    try:
        with open(JSON_FILE_PATH, 'r', encoding='utf-8') as f:
            config_data = json.load(f)
    except FileNotFoundError:
        print(f"Error: {JSON_FILE_PATH} not found. Check if 'config.json' is in the same directory as the script.")
        return
    except json.JSONDecodeError:
        print(f"Error: {JSON_FILE_PATH} contains invalid JSON.")
        return

    # 从 JSON 提取数据
    modules_data = config_data.get('CtrlModules', [])
    params_data = config_data.get('Params', [])
    params_include_data = config_data.get('params_include', [])
    modules_include_data = config_data.get('modules_include', [])
    output_params_data = config_data.get('OutputParams', [])

    # 生成 C 代码的各个部分
    print("Generating C code...")
    file_header = generate_file_header()
    
    # (将 modules_include_data 传递给 generate_includes)
    includes_section = generate_includes(modules_include_data, params_include_data)
    module_init_func = generate_module_init(modules_data)

    # 组合成完整的 C 文件内容
    full_c_code = f"""{file_header}
{includes_section}

{module_init_func}

{generate_param_init(params_data, output_params_data)}
"""

    # 写入 C 文件
    try:
        with open(C_FILE_PATH, 'w', encoding='utf-8') as f:
            f.write(full_c_code)
        print(f"Successfully generated {C_FILE_PATH}")
    except IOError as e:
        print(f"Error writing to {C_FILE_PATH}: {e}")

if __name__ == '__main__':
    main()